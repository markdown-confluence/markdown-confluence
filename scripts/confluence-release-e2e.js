import assert from "node:assert/strict";
import {
	createInlineCommentClient,
	createInlineCommentFixture,
	verifyInlineComment,
} from "./integration-comments.js";
import { fileURLToPath } from "node:url";
import { FileSystem } from "effect/FileSystem";
import { Path } from "effect/Path";
import { Console, Effect } from "effect";
import { NodeRuntime, NodeServices } from "@effect/platform-node";
import { ChildProcess } from "effect/unstable/process";
import {
	ConfluenceUploadSettings,
	MarkdownConfluencePlatformLive,
	MermaidRendererPlugin,
	PlantumlRendererPlugin,
	Publisher,
	RuntimeEnvironmentService,
	createAuthenticatedConfluenceClient,
	parseMarkdownToADF,
} from "../packages/lib/dist/index.js";
import { PuppeteerMermaidRenderer } from "../packages/mermaid-puppeteer-renderer/dist/index.js";
import { HttpPlantumlRenderer } from "../packages/plantuml-renderer/dist/index.js";
import { liveConnectionSettings } from "./integration-options.js";

const program = Effect.scoped(
	Effect.gen(function* () {
		const fs = yield* FileSystem;
		const path = yield* Path;
		const runtime = yield* RuntimeEnvironmentService;
		const environment = {};
		for (const name of [
			"ATLASSIAN_USERNAME",
			"ATLASSIAN_API_TOKEN",
			"ATLASSIAN_CLIENT_ID",
			"ATLASSIAN_CLIENT_SECRET",
			"CONFLUENCE_E2E_AUTH_TYPE",
			"CONFLUENCE_E2E_API_URL",
			"CONFLUENCE_E2E_BASE_URL",
			"CONFLUENCE_E2E_PARENT_ID",
			"CONFLUENCE_E2E_SPACE_KEY",
		])
			environment[name] = yield* runtime.getEnv(name);
		const connection = liveConnectionSettings(environment);
		const baseUrl = yield* runtime.getEnv("CONFLUENCE_E2E_BASE_URL");
		const parentId = yield* runtime.getEnv("CONFLUENCE_E2E_PARENT_ID");
		const expectedSpace = yield* runtime.getEnv("CONFLUENCE_E2E_SPACE_KEY");
		assert.ok(
			baseUrl && parentId && expectedSpace,
			"Set the dedicated test site, parent page and expected space key",
		);
		assert.equal(new URL(baseUrl).protocol, "https:", "The live test requires HTTPS");
		const runId = (yield* runtime.getEnv("GITHUB_RUN_ID")) ?? String(Date.now());
		const attempt = (yield* runtime.getEnv("GITHUB_RUN_ATTEMPT")) ?? "1";
		const prefix = `CLI E2E ${runId}-${attempt} `;
		const root = yield* fs.makeTempDirectoryScoped({ prefix: "confluence-e2e-" });
		const source = fileURLToPath(new URL("../test-fixtures/release-vault/", import.meta.url));
		yield* fs.copy(source, root, { overwrite: true });
		for (const relativePath of yield* fs.readDirectory(root, { recursive: true })) {
			if (!relativePath.endsWith(".md")) continue;
			const filename = path.join(root, relativePath);
			const markdown = yield* fs.readFileString(filename);
			yield* fs.writeFileString(
				filename,
				markdown.replace(
					/^connie-title: (.+)$/m,
					(_match, title) => `connie-title: ${prefix}${title}`,
				),
			);
		}
		yield* fs.rename(path.join(root, "Tagged"), path.join(root, `${prefix}Tagged`));
		const settings = {
			...ConfluenceUploadSettings.DEFAULT_SETTINGS,
			...connection,
			contentRoot: root,
			folderToPublish: "Release Tests",
			tagsToPublish: "release-test",
			pageHeaderMarkdown: "Generated by the Confluence release verification.",
			pageFooterMarkdown: "End of release verification.",
			ignoredCodeBlockLanguages: ["dataview", "button"],
			mermaidProtocolTimeout: 600000,
			plantuml: { enabled: true, serverUrl: "https://www.plantuml.com/plantuml" },
		};
		const client = yield* createAuthenticatedConfluenceClient(settings);
		const parent = yield* Effect.tryPromise(() =>
			client.content.getContentById({ id: parentId, expand: ["space"] }),
		);
		assert.equal(
			parent.space?.key,
			expectedSpace,
			"Refusing to publish outside the dedicated test space",
		);
		const ownedParent = yield* Effect.tryPromise(() =>
			client.content.createContent({
				type: "page",
				title: `${prefix}Run`,
				space: { key: expectedSpace },
				ancestors: [{ id: parentId }],
				body: {
					atlas_doc_format: {
						representation: "atlas_doc_format",
						value: JSON.stringify({ type: "doc", version: 1, content: [] }),
					},
				},
			}),
		);
		settings.confluenceParentId = ownedParent.id;
		const commenter = yield* createInlineCommentClient(client, settings);

		const fetchedPages = new Map();
		const updateComparisons = new Map();
		const getContentById = client.content.getContentById.bind(client.content);
		client.content.getContentById = async (parameters) => {
			const page = await getContentById(parameters);
			if (page.body?.atlas_doc_format?.value)
				fetchedPages.set(parameters.id, structuredClone(page));
			return page;
		};
		const requestedBodies = new Map();
		const updateContent = client.content.updateContent.bind(client.content);
		client.content.updateContent = async (parameters) => {
			requestedBodies.set(parameters.id, parameters.body?.atlas_doc_format?.value);
			updateComparisons.set(parameters.id, {
				previous: fetchedPages.get(parameters.id),
				requested: structuredClone(parameters),
			});
			return updateContent(parameters);
		};
		const publisher = new Publisher(settings, client, [
			new MermaidRendererPlugin(
				new PuppeteerMermaidRenderer({ protocolTimeout: settings.mermaidProtocolTimeout }),
			),
			new PlantumlRendererPlugin(
				new HttpPlantumlRenderer({ serverUrl: settings.plantuml.serverUrl }),
			),
		]);
		const publish = () =>
			Effect.tryPromise(async () => {
				const results = await publisher.publish();
				const failures = results.filter((result) => !result.successfulUploadResult);
				assert.equal(
					failures.length,
					0,
					failures
						.map((result) => `${result.node.file.pageTitle}: ${result.reason}`)
						.join("\n"),
				);
				return results;
			});
		const fetchPage = (id) =>
			Effect.tryPromise(() =>
				client.content.getContentById({
					id,
					expand: ["body.atlas_doc_format", "version", "ancestors", "space"],
				}),
			);
		const first = yield* publish();
		assert.ok(first.length >= 7, "The folder, nested notes and tagged note must publish");
		const byTitle = new Map(first.map((result) => [result.node.file.pageTitle, result]));
		const named = (title) => {
			const result = byTitle.get(prefix + title);
			assert.ok(result, `Missing published fixture: ${title}`);
			return result.node.file;
		};
		const formatting = named("Obsidian Formatting");
		const media = named("Obsidian Media");
		const embeds = named("Obsidian Embeds");
		const hierarchy = named("Obsidian Hierarchy");
		const child = named("Obsidian Child");
		named("Obsidian Tagged Selection");
		assert.ok(
			![...byTitle.keys()].some((title) => /Excluded|Unselected/.test(title)),
			"Excluded notes must not publish",
		);
		const versions = new Map();
		const storedBodies = new Map();
		for (const result of first) {
			const file = result.node.file;
			const page = yield* fetchPage(file.pageId);
			assert.equal(page.space?.key, expectedSpace);
			versions.set(file.pageId, page.version.number);
			storedBodies.set(file.pageId, page.body.atlas_doc_format.value);
			// Synthetic folder containers use the standard child-page listing, not source Markdown.
			if (!file.absoluteFilePath.toLowerCase().endsWith(".md")) continue;
			const body = page.body.atlas_doc_format.value;
			assert.ok(
				body.includes("Generated by the Confluence release verification."),
				`Missing header: ${file.pageTitle}`,
			);
			assert.ok(
				body.includes("End of release verification."),
				`Missing footer: ${file.pageTitle}`,
			);
		}
		const formattingPage = yield* fetchPage(formatting.pageId);
		const formattingAdf = JSON.stringify(
			JSON.parse(formattingPage.body.atlas_doc_format.value),
		);
		for (const expected of [
			'"type":"strong"',
			'"type":"panel"',
			'"extensionKey":"toc"',
			"中文 café ✓",
			"Formatted",
			"Local heading",
		]) {
			assert.ok(formattingAdf.includes(expected), `Formatting lost: ${expected}`);
		}
		assert.ok(!formattingAdf.includes("THIS BLOCK MUST NOT BE PUBLISHED"));
		const embedsPage = yield* fetchPage(embeds.pageId);
		assert.ok(embedsPage.body.atlas_doc_format.value.includes("EMBEDDED SECTION CONTENT."));
		assert.ok(
			!embedsPage.body.atlas_doc_format.value.includes("THIS SECTION MUST NOT BE EMBEDDED."),
		);
		assert.ok(!embedsPage.body.atlas_doc_format.value.includes("This lead-in must not appear"));
		const childPage = yield* fetchPage(child.pageId);
		assert.equal(
			childPage.ancestors.at(-1).id,
			hierarchy.pageId,
			"The folder note must be the child's parent",
		);
		const mediaPage = yield* fetchPage(media.pageId);
		for (const text of [
			"Before the first image.",
			"Between images.",
			"After the images.",
			"Final list item",
		]) {
			assert.ok(
				mediaPage.body.atlas_doc_format.value.includes(text),
				`Media conversion lost text: ${text}`,
			);
		}
		const attachments = yield* Effect.tryPromise(() =>
			client.contentAttachments.getAttachments({ id: media.pageId, limit: 250 }),
		);
		assert.ok(
			attachments.results.length >= 5,
			"Images, file attachments, Mermaid and PlantUML must be uploaded",
		);
		assert.ok(
			attachments.results.some((attachment) =>
				attachment.title.startsWith("RenderedMermaidChart-"),
			),
		);
		assert.ok(
			attachments.results.some((attachment) =>
				attachment.title.startsWith("RenderedPlantumlChart-"),
			),
		);
		const labels = yield* Effect.tryPromise(() =>
			client.contentLabels.getLabelsForContent({ id: formatting.pageId, limit: 250 }),
		);
		assert.ok(labels.results.some((label) => label.name === "formatting"));
		const formattingPath = path.join(root, "Release Tests/Formatting.md");
		const localFormatting = yield* fs.readFileString(formattingPath);
		assert.ok(
			localFormatting.includes("connie-page-url:"),
			"Publishing must save the page URL in frontmatter",
		);
		assert.ok(localFormatting.includes(formatting.pageId));

		requestedBodies.clear();
		yield* Console.log(
			"[confluence] Verify unchanged content, attachments, labels and versions",
		);
		const second = yield* publish();
		for (const result of second) {
			if (result.successfulUploadResult.contentResult !== "same") {
				yield* Console.log(
					JSON.stringify({
						title: result.node.file.pageTitle,
						comparison: updateComparisons.get(result.node.file.pageId),
						existingPageData: result.node.existingPageData,
						storedBody: JSON.parse(storedBodies.get(result.node.file.pageId)),
						requestedBody: JSON.parse(requestedBodies.get(result.node.file.pageId)),
					}),
				);
			}
		}
		for (const result of second) {
			assert.equal(
				result.successfulUploadResult.contentResult,
				"same",
				`Unchanged content was updated: ${result.node.file.pageTitle}`,
			);
			assert.equal(
				result.successfulUploadResult.imageResult,
				"same",
				`Unchanged attachments were uploaded: ${result.node.file.pageTitle}`,
			);
			assert.equal(
				result.successfulUploadResult.labelResult,
				"same",
				`Unchanged labels were updated: ${result.node.file.pageTitle}`,
			);
			const page = yield* fetchPage(result.node.file.pageId);
			assert.equal(
				page.version.number,
				versions.get(page.id),
				`Unchanged page version advanced: ${page.title}`,
			);
		}
		const inlineComment = yield* Effect.tryPromise(() =>
			createInlineCommentFixture(commenter, formatting.pageId),
		);
		yield* Console.log(
			`Created inline comment ${inlineComment.commentId} on page ${formatting.pageId}`,
		);

		yield* fs.writeFileString(
			formattingPath,
			`${localFormatting}\n\nUPDATED END TO END SENTINEL.\n`,
		);
		const third = yield* publish();
		for (const result of third) {
			const changed = result.node.file.pageId === formatting.pageId;
			assert.equal(result.successfulUploadResult.contentResult, changed ? "updated" : "same");
		}
		const updated = yield* fetchPage(formatting.pageId);
		assert.ok(updated.version.number > versions.get(formatting.pageId));
		assert.ok(updated.body.atlas_doc_format.value.includes("UPDATED END TO END SENTINEL."));
		const inlineCommentEvidence = yield* Effect.tryPromise(() =>
			verifyInlineComment(commenter, inlineComment),
		);

		versions.set(formatting.pageId, updated.version.number);
		const cliConfig = path.join(root, ".markdown-confluence.json");
		yield* fs.writeFileString(
			cliConfig,
			JSON.stringify({
				...settings,
				atlassianApiToken: undefined,
				atlassianClientSecret: undefined,
			}),
		);
		const cliPath = fileURLToPath(new URL("../packages/cli/dist/index.js", import.meta.url));
		const conversionConfig = path.join(root, "read-only-conversion.json");
		yield* fs.writeFileString(
			conversionConfig,
			JSON.stringify({
				...settings,
				confluenceParentId: "",
				atlassianApiToken: undefined,
				atlassianClientSecret: undefined,
			}),
		);
		const exportedAdfPath = path.join(root, "exported.adf.json");
		const exportedMarkdownPath = path.join(root, "exported.md");
		const pageUrl = `${baseUrl}/wiki/spaces/${expectedSpace}/pages/${media.pageId}`;
		for (const args of [
			["to-adf", pageUrl, "--output", exportedAdfPath],
			["to-markdown", "--page", media.pageId, "--output", exportedMarkdownPath],
		]) {
			const conversion = yield* ChildProcess.make(
				"node",
				[cliPath, ...args, "--config", conversionConfig],
				{
					cwd: root,
					extendEnv: true,
					stdout: "inherit",
					stderr: "inherit",
				},
			);
			assert.equal(
				yield* conversion.exitCode,
				0,
				`Conversion command ${args[0]} must succeed without a parent ID`,
			);
		}
		const exportedAdf = JSON.parse(yield* fs.readFileString(exportedAdfPath));
		assert.deepEqual(
			exportedAdf,
			JSON.parse((yield* fetchPage(media.pageId)).body.atlas_doc_format.value),
		);
		assert.deepEqual(
			parseMarkdownToADF(yield* fs.readFileString(exportedMarkdownPath), baseUrl),
			exportedAdf,
			"Live Confluence Markdown export must preserve attachment IDs and every ADF field",
		);
		yield* fs.remove(exportedMarkdownPath);
		yield* Console.log(
			"[confluence] Both CLI exports passed; exact Markdown/ADF round trip and read-only behavior verified below",
		);
		const cliProcess = yield* ChildProcess.make("node", [cliPath, "--config", cliConfig], {
			cwd: root,
			extendEnv: true,
			stdout: "inherit",
			stderr: "inherit",
		});
		assert.equal(yield* cliProcess.exitCode, 0, "The built CLI must publish successfully");
		for (const [pageId, version] of versions) {
			const page = yield* fetchPage(pageId);
			assert.equal(
				page.version.number,
				version,
				`CLI republishing changed an unchanged page: ${page.title}`,
			);
		}

		const duplicatePath = path.join(root, "Release Tests/Duplicate.md");
		yield* fs.writeFileString(
			duplicatePath,
			`---\nconnie-title: ${formatting.pageTitle}\n---\nDuplicate title without a page ID.\n`,
		);
		requestedBodies.clear();
		yield* Effect.tryPromise(() =>
			assert.rejects(() => publisher.publish(), /is not unique across all files/),
		);
		assert.equal(requestedBodies.size, 0, "Duplicate titles must fail before page updates");
		yield* fs.remove(duplicatePath);

		const validFormatting = yield* fs.readFileString(formattingPath);
		yield* fs.writeFileString(
			formattingPath,
			`${validFormatting}\n![[Source Notes/Reusable#Missing release-test heading]]\n`,
		);
		yield* Effect.tryPromise(() =>
			assert.rejects(
				() => publisher.publish(),
				/Embedded Markdown section or block not found/,
			),
		);
		assert.equal(
			requestedBodies.size,
			0,
			"Missing embed headings must fail before page updates",
		);
		yield* fs.writeFileString(formattingPath, validFormatting);
		for (const [pageId, version] of versions) {
			const page = yield* fetchPage(pageId);
			assert.equal(
				page.version.number,
				version,
				`Rejected notes changed page: ${page.title}`,
			);
		}

		// Inject a transport failure against a real fixture, then reuse the same publisher.
		const recoveryMarkdown = `${validFormatting}\nRECOVERED AFTER UPLOAD FAILURE.\n`;
		yield* fs.writeFileString(formattingPath, recoveryMarkdown);
		let injectedFailures = 0;
		client.content.updateContent = async (parameters) => {
			assert.equal(parameters.id, formatting.pageId);
			injectedFailures++;
			throw new Error("Injected release-test transport failure");
		};
		const publishFormatting = () => publisher.publish(formatting.absoluteFilePath);
		const failedUpload = yield* Effect.tryPromise(publishFormatting);
		assert.equal(injectedFailures, 1);
		assert.equal(failedUpload.length, 1);
		assert.equal(failedUpload[0].successfulUploadResult, undefined);
		assert.match(failedUpload[0].reason, /Injected release-test transport failure/);
		const afterFailure = yield* fetchPage(formatting.pageId);
		assert.equal(afterFailure.version.number, versions.get(formatting.pageId));
		assert.ok(
			!afterFailure.body.atlas_doc_format.value.includes("RECOVERED AFTER UPLOAD FAILURE."),
		);
		client.content.updateContent = updateContent;
		const recovered = yield* Effect.tryPromise(publishFormatting);
		assert.equal(recovered[0].successfulUploadResult?.contentResult, "updated");
		const recoveredPage = yield* fetchPage(formatting.pageId);
		assert.ok(
			recoveredPage.body.atlas_doc_format.value.includes("RECOVERED AFTER UPLOAD FAILURE."),
		);

		// Advance the real page between the version read and write to provoke an HTTP 409.
		yield* fs.writeFileString(
			formattingPath,
			`${recoveryMarkdown}\nRECOVERED AFTER VERSION CONFLICT.\n`,
		);
		let conflictAttempts = 0;
		client.content.updateContent = async (parameters) => {
			assert.equal(parameters.id, formatting.pageId);
			conflictAttempts++;
			if (conflictAttempts === 1) {
				await updateContent({
					...parameters,
					body: {
						atlas_doc_format: {
							representation: "atlas_doc_format",
							value: recoveredPage.body.atlas_doc_format.value,
						},
					},
				});
			}
			return updateContent(parameters);
		};
		const conflictRecovery = yield* Effect.tryPromise(publishFormatting);
		assert.equal(conflictAttempts, 2, "Publishing must retry the stale version once");
		assert.equal(conflictRecovery[0].successfulUploadResult?.contentResult, "updated");
		client.content.updateContent = updateContent;
		const conflictPage = yield* fetchPage(formatting.pageId);
		assert.equal(conflictPage.version.number, recoveredPage.version.number + 2);
		assert.ok(
			conflictPage.body.atlas_doc_format.value.includes("RECOVERED AFTER VERSION CONFLICT."),
		);
		let finalRequestedBody;
		client.content.updateContent = async (parameters) => {
			finalRequestedBody = parameters.body?.atlas_doc_format?.value;
			updateComparisons.set(parameters.id, {
				previous: fetchedPages.get(parameters.id),
				requested: structuredClone(parameters),
			});
			return updateContent(parameters);
		};
		const finalPublish = yield* Effect.tryPromise(publishFormatting);
		if (finalPublish[0].successfulUploadResult?.contentResult !== "same") {
			yield* Console.log(
				JSON.stringify({
					check: "unchanged-after-conflict",
					storedBody: conflictPage.body.atlas_doc_format.value,
					requestedBody: finalRequestedBody,
					comparison: updateComparisons.get(formatting.pageId),
					existingPageData: finalPublish[0].node.existingPageData,
				}),
			);
		}
		client.content.updateContent = updateContent;
		assert.equal(finalPublish[0].successfulUploadResult?.contentResult, "same");
		assert.equal(
			(yield* fetchPage(formatting.pageId)).version.number,
			conflictPage.version.number,
		);
		yield* Effect.tryPromise(() => verifyInlineComment(commenter, inlineComment));

		const pageLinks = first
			.map((result) => `- [${result.node.file.pageTitle}](${result.node.file.pageUrl})`)
			.join("\n");
		const summary = `## Confluence release verification passed\n\nCreated/verified ${first.length} pages; unchanged publishing preserved content, attachments, labels and versions; one changed note updated successfully; the built CLI republished without further changes. Duplicate titles and missing embed headings were rejected without page updates. The same publisher recovered from an injected transport failure and a real HTTP version conflict, then preserved the unchanged page version. A real inline comment retained its ID, body, open status and highlighted text after an edit elsewhere on the page and subsequent CLI publishing.\n\n${pageLinks}\n`;
		const summaryPath = yield* runtime.getEnv("GITHUB_STEP_SUMMARY");
		if (summaryPath) yield* fs.writeFileString(summaryPath, summary, { flag: "a" });
		const reportPath = yield* runtime.getEnv("CONFLUENCE_E2E_REPORT_PATH");
		if (reportPath)
			yield* fs.writeFileString(
				reportPath,
				JSON.stringify(
					{
						status: "passed",
						inlineComment: inlineCommentEvidence,
						checks: [
							"create",
							"formatting",
							"embeds",
							"hierarchy",
							"selection",
							"attachments",
							"unchanged",
							"update",
							"built-cli",
							"duplicate-title",
							"missing-embed",
							"transport-recovery",
							"version-conflict",
							"inline-comments-preserved",
						],
						pages: first.map((result) => ({
							id: result.node.file.pageId,
							title: result.node.file.pageTitle,
							url: result.node.file.pageUrl,
						})),
					},
					null,
					2,
				),
			);
		yield* Console.log(summary);
	}),
);

if (import.meta.main) {
	NodeRuntime.runMain(
		program.pipe(
			Effect.catch((error) =>
				Effect.fail(
					new Error(
						error?.cause instanceof Error
							? error.cause.message
							: error instanceof Error
								? error.message
								: "Confluence release verification failed",
					),
				),
			),
			Effect.provide(NodeServices.layer),
			Effect.provide(MarkdownConfluencePlatformLive),
		),
	);
}
